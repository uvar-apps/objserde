#!/usr/bin/env python3
"""Regenerate the 1M-vertex OBJ budget proxy at /tmp/million_sphere.obj.

The same construction meshview times its loader against: a closed UV sphere
(nu=1414, nv=707, r=17.5), vertices and outward analytic normals, faces in the
`f i//i` form with six-decimal coordinates — ~1,001,112 vertices,
~1,999,396 triangles, ~160 MB of text. Vertex i carries normal i, so loading
exercises the `vn` binding path rather than the geometric fallback.

    python3 assets/perf/gen_million_sphere.py [outfile]

Then time the crate against it:

    cargo test --release --test perf -- --ignored --nocapture
"""

import sys
import time

import numpy as np

NU = 1414
NV = 707
RADIUS = 17.5
OUT = sys.argv[1] if len(sys.argv) > 1 else "/tmp/million_sphere.obj"
ROWS = 200_000


def lines_of(prefix: str, xyz) -> str:
    """One `v a b c` (or `vn`) line per row, six decimals as the writers emit."""
    return "".join(
        "%s %.6f %.6f %.6f\n" % (prefix, row[0], row[1], row[2]) for row in xyz
    )


def main() -> None:
    started = time.perf_counter()

    theta = np.pi * np.arange(NV + 1, dtype=np.float64)[:, None] / NV
    phi = 2.0 * np.pi * np.arange(NU, dtype=np.float64)[None, :] / NU
    st, ct = np.sin(theta), np.cos(theta)
    sp, cp = np.sin(phi), np.cos(phi)

    shape = (NV + 1, NU)
    nx = st * cp
    ny = st * np.broadcast_to(sp, shape)
    nz = np.broadcast_to(ct, shape)
    normals = np.stack([nx, ny, nz], axis=-1).reshape(-1, 3)
    positions = (normals * RADIUS).copy()

    n_faces = 2 * NV * NU
    with open(OUT, "w", buffering=1 << 22) as out:
        out.write("# generated by assets/perf/gen_million_sphere.py\n")
        out.write(f"# uv sphere nu={NU} nv={NV} r={RADIUS}\n")
        out.write(f"# vertices: {positions.shape[0]}  triangles: {n_faces}\n")

        for start in range(0, positions.shape[0], ROWS):
            out.write(lines_of("v", positions[start : start + ROWS]))
        for start in range(0, normals.shape[0], ROWS):
            out.write(lines_of("vn", normals[start : start + ROWS]))
        del positions, normals

        # Same order as the reference generator: per grid cell, [a, c, b] then
        # [b, c, d], where the u index wraps so the sphere is closed.
        idx = np.arange(shape[0] * NU, dtype=np.int64).reshape(shape)
        for start in range(0, NV, ROWS // NU):
            stop = min(start + ROWS // NU, NV)
            a = idx[start:stop]
            b = np.roll(a, -1, axis=1)
            c = idx[start + 1 : stop + 1]
            d = np.roll(c, -1, axis=1)
            tri = np.stack(
                [np.stack([a, c, b], axis=-1), np.stack([b, c, d], axis=-1)],
                axis=2,
            ).reshape(-1, 3) + 1
            out.write(
                "".join(
                    "f %d//%d %d//%d %d//%d\n" % (r[0], r[0], r[1], r[1], r[2], r[2])
                    for r in tri.tolist()
                )
            )

    print(f"wrote {OUT} in {time.perf_counter() - started:.1f}s")


if __name__ == "__main__":
    main()
